import { createRequire } from 'node:module';
const require2 = createRequire(import.meta.url);
const Database = require2('better-sqlite3');
const { searchSessions } = await import('../../src/search-svc/engine.js');
const db = new Database('D:/agent1super/.sessionrelay/relay.sqlite', { readonly: true });
const PID = (db.prepare('SELECT project_id FROM sessions LIMIT 1').get() as any).project_id;
const t0 = Date.now();
const hits = searchSessions(db, { project: PID, query: '给编辑器的问题清单在哪些会话里处理过', limit: 10, rewrite: true, lengthNorm: true, coreOnly: true } as never);
console.log('ms', Date.now()-t0, 'n', hits.length);
for (const h of hits.slice(0,3)) console.log(JSON.stringify({ id: h.sessionId, score: h.score.toFixed(2), cov: h.coverage, seq: h.seq, viaMeta: h.viaMeta, snip: h.snippet.slice(0,60) }));
