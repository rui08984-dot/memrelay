import fs from 'node:fs';
const j = JSON.parse(fs.readFileSync('scripts/bench-out/xarm-aggregate.json','utf8'));
const rows = j.rows;
const has = (r) => r.goldHits > 0;
const inTop = (r) => r.rank10 >= 1;
const tab = (label, f) => {
  const sub = rows.filter(f);
  const ne = sub.length;
  const cov = (p) => sub.filter((r)=>r[p].span >= 1).length;
  const p = (x)=>String(Math.round(x/Math.max(1,ne)*1000)/10).padStart(5)+'%';
  console.log(label.padEnd(30), 'n='+String(ne).padStart(2),
    '| P0 span=1 '+p(cov('base')), '| P1 span=1 '+p(cov('p1')), '| P2 span=1 '+p(cov('p2')));
};
console.log('== 交叉表：目标是否在 top-10 × 证据覆盖（分母=桶内全部题） ==');
tab('目标在 top-10', r=>inTop(r));
tab('目标不在 top-10', r=>!inTop(r));
tab('  其中 rank11-50', r=>!inTop(r) && r.rankDeep>=1);
tab('  其中 >50/不可达', r=>r.rankDeep===0);
tab('全部', r=>true);
console.log('');
const notIn = rows.filter((r)=>!inTop(r) && has(r));
const covered = notIn.filter((r)=>r.p1.span>=1);
console.log('目标不在 top-10 且有证据句: n='+notIn.length+', 其中 P1 证据仍被覆盖 '+covered.length+' = '+(Math.round(covered.length/notIn.length*1000)/10)+'%');
console.log('  且目标连 rank50 都没进、证据却已被覆盖: '+notIn.filter((r)=>r.p1.span>=1 && r.rankDeep===0).length);
console.log('');
const s = rows.filter(has);
console.log('严格整句命中数 P0/P1/P2:', s.filter((r)=>r.base.strict).length, s.filter((r)=>r.p1.strict).length, s.filter((r)=>r.p2.strict).length, 'n='+s.length);
const lens = s.map((r)=>r.goldLen).sort((a,b)=>a-b);
console.log('证据句长度 中位/均值/最大:', lens[Math.floor(lens.length/2)], Math.round(lens.reduce((a,b)=>a+b,0)/lens.length), lens[lens.length-1]);
console.log('证据句 >120 字占比: '+(Math.round(s.filter((r)=>r.goldLen>120).length/s.length*1000)/10)+'%');
console.log('目标在 top-10 且 P1 严格命中: '+rows.filter((r)=>inTop(r)&&r.p1.strict).length+' / '+rows.filter(inTop).length);
console.log('');
console.log('fingerprint:', j.fingerprint);
console.log('coverage:', JSON.stringify(j.summary.coverage));
console.log('chars:', JSON.stringify(j.summary.chars));
console.log('clusters:', JSON.stringify(j.summary.clusters));
console.log('byBucket:', JSON.stringify(j.summary.byBucket));
